export const findKeralaLocation = (query) => {
  if (!query) return null;
  const q = query.trim().toLowerCase();
  return (
    KERALA_LOCATIONS.find(
      (loc) =>
        loc.id === q ||
        loc.name.toLowerCase().includes(q) ||
        loc.district.toLowerCase().includes(q)
    ) || null
  );
};
